#!/usr/bin/env node

/**
 * MULE SHIELD Static Frontend Build Script
 *
 * Runs during static host build step (Vercel, Netlify, Cloudflare Pages, etc.).
 * Reads production backend URL from environment (MULE_SHIELD_API_URL, BACKEND_URL, or API_URL)
 * and safely injects it into frontend/js/config.js.
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const CONFIG_FILE = path.join(ROOT_DIR, 'frontend', 'js', 'config.js');

const apiUrl = (
  process.env.MULE_SHIELD_API_URL ||
  process.env.BACKEND_URL ||
  process.env.API_URL ||
  ""
).trim().replace(/\/+$/, '');

console.log('=== MULE SHIELD Static Frontend Build ===');

if (apiUrl) {
  console.log(`[Config] Injected production API base URL: ${apiUrl}`);
  const configContent = `/**
 * MULE SHIELD Enterprise Cloud Deployment Configuration
 * Auto-generated by build script on ${new Date().toISOString()}
 */
window.__MULE_SHIELD_CONFIG__ = Object.assign(
  {
    API_BASE_URL: ${JSON.stringify(apiUrl)}
  },
  window.__MULE_SHIELD_CONFIG__ || {}
);
`;
  fs.writeFileSync(CONFIG_FILE, configContent, 'utf8');
} else {
  console.log('[Config] No production API URL provided in build environment.');
  console.log('         API calls will default to runtime config or relative paths.');
  console.log('         (Can be configured at runtime in frontend/js/config.js or via meta tag)');
}

console.log('=== Build complete ===\n');
